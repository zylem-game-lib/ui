import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { Window } from 'happy-dom';

const root = new URL('../src/icons/custom/', import.meta.url);
const manifest = JSON.parse(await readFile(new URL('manifest.json', root), 'utf8'));
const check = process.argv.includes('--check');
const parser = new (new Window()).DOMParser();
const generated = '// Generated by scripts/generate-custom-icons.mjs. Edit the source SVGs instead.\n';
const pascal = (id) => id.split('-').map((part) => part[0].toUpperCase() + part.slice(1)).join('');
const componentName = (item) => `${item.category === 'genres' ? 'Genre' : 'Behavior'}${pascal(item.id)}`;
const allowedTags = new Set(['g', 'path', 'rect', 'circle']);
const allowedAttrs = new Set(['d', 'x', 'y', 'width', 'height', 'rx', 'ry', 'cx', 'cy', 'r', 'transform', 'fill', 'stroke', 'stroke-width', 'stroke-dasharray']);

function node(element) {
  assert(allowedTags.has(element.localName), `Unsupported SVG element: ${element.localName}`);
  const attrs = {};
  for (const attr of element.attributes) {
    assert(allowedAttrs.has(attr.name), `Unsupported SVG attribute: ${attr.name}`);
    attrs[attr.name] = attr.value;
  }
  const children = [...element.children].map(node);
  return children.length ? [element.localName, attrs, children] : [element.localName, attrs];
}

async function output(name, contents) {
  contents = `${contents.trimEnd()}\n`;
  const url = new URL(name, root);
  if (check) assert.equal(await readFile(url, 'utf8'), contents, `${name} is stale. Run pnpm icons:generate.`);
  else await writeFile(url, contents);
}

assert.equal(new Set(manifest.icons.map((item) => item.key)).size, manifest.icons.length);
assert.equal(new Set(manifest.icons.map(componentName)).size, manifest.icons.length);
for (const category of ['genres', 'behaviors']) {
  let contents = `${generated}import { createZylemIcon } from '../create-icon';\n\n`;
  for (const item of manifest.icons.filter((entry) => entry.category === category)) {
    assert.match(item.id, /^[a-z0-9-]+$/);
    assert.equal(item.path, `${category}/${item.id}.svg`);
    const svgText = await readFile(new URL(`svg/${item.path}`, root), 'utf8');
    const svg = parser.parseFromString(svgText, 'image/svg+xml').documentElement;
    assert.equal(svg.localName, 'svg');
    assert.equal(svg.getAttribute('viewBox'), '0 0 64 64');
    assert.equal(svg.getAttribute('stroke'), 'currentColor');
    const nodes = [...svg.children].filter((element) => element.localName !== 'title').map(node);
    assert(nodes.length > 0);
    contents += `export const ${componentName(item)} = /* @__PURE__ */ createZylemIcon(\n`;
    contents += `  ${JSON.stringify(componentName(item))},\n  ${JSON.stringify(nodes)},\n`;
    contents += `  { className: 'zylem-custom-icon', viewBox: '0 0 64 64', defaultSize: 64, defaultStrokeWidth: 3 },\n);\n\n`;
  }
  await output(`${category}.ts`, contents);
}

let catalog = `${generated}import type { Component } from 'solid-js';\nimport type { ZylemIconProps } from '../create-icon';\nimport * as genres from './genres';\nimport * as behaviors from './behaviors';\n\n`;
catalog += `export interface CustomIconEntry {\n  id: string;\n  key: string;\n  label: string;\n  category: 'genres' | 'behaviors';\n  exportName: string;\n  description: string;\n  aliases: readonly string[];\n  Icon: Component<ZylemIconProps>;\n}\n\n`;
for (const [category, exportName] of [['genres', 'GENRE_ICONS'], ['behaviors', 'BEHAVIOR_ICONS']]) {
  catalog += `export const ${exportName} = [\n`;
  for (const item of manifest.icons.filter((entry) => entry.category === category)) {
    const aliases = new Set(item.sourceIds);
    for (const mapping of ['genreGraphIds', 'repositoryGenreIds', 'behaviorIds', 'apiAliases', 'mechanicIds']) {
      for (const [alias, key] of Object.entries(manifest[mapping])) if (key === item.key) aliases.add(alias);
    }
    const entry = { id: item.id, key: item.key, label: item.label, category, exportName: componentName(item), description: item.description, aliases: [...aliases] };
    catalog += `  ${JSON.stringify(entry).slice(0, -1)}, Icon: ${category}.${componentName(item)} },\n`;
  }
  catalog += `] as const satisfies readonly CustomIconEntry[];\n\n`;
}
for (const mapping of ['genreGraphIds', 'repositoryGenreIds', 'behaviorIds', 'apiAliases', 'mechanicIds']) {
  catalog += `export const ${mapping} = ${JSON.stringify(manifest[mapping], null, 2)} as const;\n\n`;
}
await output('catalog.ts', catalog);
console.log(`${check ? 'Verified' : 'Generated'} ${manifest.icons.length} custom icon components and catalog mappings.`);
