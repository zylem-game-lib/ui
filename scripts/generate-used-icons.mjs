import assert from 'node:assert/strict';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import ts from 'typescript';

const root = new URL('../', import.meta.url);
const output = new URL('showcase/src/used-icons.ts', root);
const names = new Set();
for (const directory of ['src/', 'showcase/src/']) {
  const base = new URL(directory, root);
  for (const path of await readdir(base, { recursive: true })) {
    if (!/\.tsx?$/.test(path)) continue;
    const url = new URL(path, base);
    if (url.href === output.href) continue;
    const source = ts.createSourceFile(path, await readFile(url, 'utf8'), ts.ScriptTarget.Latest);
    for (const statement of source.statements) {
      if (!ts.isImportDeclaration(statement) || !ts.isStringLiteral(statement.moduleSpecifier)) continue;
      const match = /^lucide-solid\/icons\/([a-z0-9-]+)$/.exec(statement.moduleSpecifier.text);
      if (match) names.add(match[1]);
      assert.notEqual(statement.moduleSpecifier.text, 'lucide-solid', 'Use Lucide per-icon imports so the showcase can inventory the exact set.');
    }
  }
}
const pascal = (name) => name.split('-').map((part) => part[0].toUpperCase() + part.slice(1)).join('');
let text = '// Generated by scripts/generate-used-icons.mjs from actual imports.\n';
for (const name of [...names].sort()) text += `import ${pascal(name)} from 'lucide-solid/icons/${name}';\n`;
text += `import type { Component } from 'solid-js';\n\nexport interface UsedIcon {\n  name: string;\n  label: string;\n  Icon: Component<{ size?: number }>;\n}\n\nexport const USED_LUCIDE_ICONS: readonly UsedIcon[] = [\n`;
for (const name of [...names].sort()) {
  const label = name.split('-').map((part) => part[0].toUpperCase() + part.slice(1)).join(' ');
  text += `  { name: '${name}', label: '${label}', Icon: ${pascal(name)} },\n`;
}
text += '];\n';
if (process.argv.includes('--check')) assert.equal(await readFile(output, 'utf8'), text, 'Lucide inventory is stale. Run pnpm icons:generate.');
else await writeFile(output, text);
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Generated'} ${names.size} used Lucide icons.`);
